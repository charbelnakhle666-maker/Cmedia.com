create table if not exists public.appointment_inquiries (
  id bigint generated by default as identity primary key,
  full_name text not null,
  email text not null,
  phone_number text not null,
  business_type text not null,
  appointment_date date not null,
  status text not null default 'pending' check (status in ('pending', 'confirmed', 'declined')),
  created_at timestamptz not null default now(),
  calendar_event_id text,
  calendar_synced_at timestamptz
);

alter table public.appointment_inquiries
  add column if not exists phone_number text,
  add column if not exists calendar_event_id text,
  add column if not exists calendar_synced_at timestamptz;

create index if not exists appointment_inquiries_date_status_idx
  on public.appointment_inquiries (appointment_date, status);

create unique index if not exists appointment_inquiries_one_confirmed_per_day
  on public.appointment_inquiries (appointment_date)
  where status = 'confirmed';

alter table public.appointment_inquiries enable row level security;

create table if not exists public.microsoft_calendar_credentials (
  id smallint primary key check (id = 1),
  access_token text not null,
  refresh_token text not null,
  expires_at timestamptz not null,
  microsoft_user_email text not null default '',
  microsoft_display_name text not null default '',
  updated_at timestamptz not null default now()
);

alter table public.microsoft_calendar_credentials enable row level security;
revoke all on public.microsoft_calendar_credentials from anon, authenticated;
grant all on public.microsoft_calendar_credentials to service_role;

create table if not exists public.microsoft_calendar_oauth_states (
  state_hash text primary key,
  expires_at timestamptz not null
);

create index if not exists microsoft_calendar_oauth_states_expires_at_idx
  on public.microsoft_calendar_oauth_states (expires_at);

alter table public.microsoft_calendar_oauth_states enable row level security;
revoke all on public.microsoft_calendar_oauth_states from anon, authenticated;
grant all on public.microsoft_calendar_oauth_states to service_role;
